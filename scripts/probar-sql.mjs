let fallas = 0
const ok = (cond, texto) => { console.log(`${cond ? '  ✓' : '  ✗'} ${texto}`); if (!cond) fallas++ }
const falla = async (texto, fn) => {
  try { await fn(); ok(false, `${texto} (tenía que fallar y no falló)`) } catch (e) { ok(true, `${texto} → "${String(e.message).slice(0, 60)}"`) }
}
/** Tiene que fallar, y por ese motivo (no por cualquier error). */
const fallaPor = async (texto, motivo, fn) => {
  try { await fn(); ok(false, `${texto} (tenía que fallar y no falló)`) } catch (e) { ok(motivo.test(String(e.message)), `${texto} → "${String(e.message).slice(0, 60)}"`) }
}
const titulo = (t) => console.log(`\n${t}`)

