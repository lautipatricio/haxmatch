const jugador = (u, extra = {}) => x.rpc(u, 'crear_busqueda', { p_modo: 'jugador', p_formato: ['3v3'], p_posicion: ['Polifuncional'], p_cancha: ['Cualquiera'], p_region: ['ARG'], p_duracion: '15min', ...extra })
const sala = (u, faltan, extra = {}) => x.rpc(u, 'crear_busqueda', { p_modo: 'sala', p_formato: null, p_posicion: ['Polifuncional'], p_cancha: ['Cualquiera'], p_region: ['ARG'], p_nombre_sala: `sala de ${u.usuario}`, p_faltan: faltan, ...extra })
const estado = (u) => x.rpc(u, 'estado_cola')
const mia = async (u) => (await estado(u)).busquedas.find((b) => b.user_id === u.id)
const pedido = async (u) => (await estado(u)).mensajes.find((m) => m.a === u.id && m.estado === 'pendiente')
const partido = async (u) => (await estado(u)).matches[0]
const pedidoDe = async (u, de) => (await estado(u)).mensajes.find((m) => m.a === u.id && m.de === de.id && m.estado === 'pendiente')
/** Cómo se entra a una sala: su dueño invita al jugador y el jugador acepta. */
const invitar = async (dueno, jug) => {
  await x.rpc(dueno, 'enviar_mensaje', { p_a: jug.id })
  await x.rpc(jug, 'responder_mensaje', { p_id: (await pedidoDe(jug, dueno)).id, p_aceptar: true })
}
const limpiar = async () => {
  for (const u of [ana, beto, caro, dani, eva, fran]) await x.rpc(u, 'cancelar_busqueda')
  await x.admin(`update public.busquedas set estado = 'cancelada' where estado in ('activa', 'agrupada', 'match')`)
  await x.admin(`delete from public.matches`)
  await x.admin(`delete from public.mensajes`)
}

